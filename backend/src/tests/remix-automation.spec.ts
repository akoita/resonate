/**
 * Automation lanes (#2541, S6e of #1903): the recipe, the curves, the render
 * graph, and a real-ffmpeg check that the level and filter move where the
 * lane says. The parity block replays `remix-automation-v1.parity.json`,
 * which the web preview test also replays. Regenerate with
 * UPDATE_REMIX_AUTOMATION_FIXTURE=1 (a curve change needs a new DSP version).
 */
import { execFileSync, spawnSync } from "child_process";
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { deriveSectionGrid } from "../modules/remix/remix-arrangement";
import {
  REMIX_AUTOMATION_SCHEMA_VERSION,
  automationFilters,
  filterCutoffs,
  filterSteps,
  laneValueAt,
  normalizeRemixAutomationInput,
  parseRemixAutomation,
  timedStemAutomation,
  type RemixAutomation,
} from "../modules/remix/remix-automation";
import { timelineDownbeats } from "../modules/remix/remix-cues";
import { structureTimeline } from "../modules/remix/remix-structure";
import { buildStemMixFfmpegArgs } from "../modules/remix/stem-audio-mixer";

const FIXTURE_PATH = join(
  __dirname,
  "../modules/remix/remix-automation-v1.parity.json",
);
const FFMPEG =
  spawnSync("ffmpeg", ["-version"], { stdio: "ignore" }).status === 0;
const EPS = 1e-9;

const stems = [
  {
    audioFeatures: {
      schemaVersion: "stem-audio-features/v1",
      tempoBpm: 120,
      tempoConfidence: 0.9,
      firstBeatSec: 0.5,
      durationSeconds: 64,
    },
  },
];
const blocks = [
  { section: 0 },
  { section: 1 },
  { section: 1 },
  { section: 2 },
  { section: 3 },
];
const speed = 1.25;
const automation: RemixAutomation = {
  schemaVersion: REMIX_AUTOMATION_SCHEMA_VERSION,
  stems: {
    bass: {
      level: [
        { bar: 0, value: -24 },
        { bar: 4, value: 0 },
        { bar: 20, value: 0 },
        { bar: 24, value: -12 },
      ],
      filter: [
        { bar: 8, value: 0 },
        { bar: 12, value: -0.8 },
        { bar: 16, value: 0.5 },
      ],
    },
    vocals: { filter: [{ bar: 2, value: 0.3 }] },
  },
};

function buildFixture() {
  const grid = deriveSectionGrid(stems as never)!;
  const segments = structureTimeline(grid, blocks);
  const downbeats = timelineDownbeats(grid, segments);
  const bass = timedStemAutomation(automation, "bass", downbeats, speed)!;
  const end = segments[segments.length - 1].outEndSec / speed;
  const samples = Array.from(
    { length: 41 },
    (_, i) => Math.round(((end * i) / 40) * 1e6) / 1e6,
  );
  return {
    schemaVersion: REMIX_AUTOMATION_SCHEMA_VERSION,
    note: "Generated by backend/src/tests/remix-automation.spec.ts (UPDATE_REMIX_AUTOMATION_FIXTURE=1). Replayed by web/src/lib/remixAutomation.test.ts.",
    grid: {
      bpm: grid.bpm,
      firstBeatSec: grid.firstBeatSec,
      sections: grid.sections,
    },
    blocks,
    speed,
    automation,
    downbeats,
    bass,
    samples: samples.map((t) => ({
      atSec: t,
      levelDb: laneValueAt(bass.level!, t),
      filter: laneValueAt(bass.filter!, t),
      ...filterCutoffs(laneValueAt(bass.filter!, t)),
    })),
    filterSteps: filterSteps(bass.filter!),
  };
}

describe("automation recipe (#2541)", () => {
  it("normalizes: sorts points, snaps values, drops empty lanes", () => {
    expect(
      normalizeRemixAutomationInput(
        {
          stems: {
            bass: {
              level: [
                { bar: 4, value: -3.26 },
                { bar: 0, value: 0 },
              ],
              filter: [],
            },
            vocals: {},
          },
        },
        ["bass", "vocals"],
      ),
    ).toEqual({
      schemaVersion: REMIX_AUTOMATION_SCHEMA_VERSION,
      stems: {
        bass: {
          level: [
            { bar: 0, value: 0 },
            { bar: 4, value: -3.5 },
          ],
        },
      },
    });
    expect(normalizeRemixAutomationInput({ stems: {} }, ["bass"])).toBeNull();
    expect(normalizeRemixAutomationInput(null, ["bass"])).toBeNull();
  });

  it.each([
    ["a string", "x"],
    [
      "an unknown stem",
      { stems: { drums: { level: [{ bar: 0, value: 0 }] } } },
    ],
    [
      "a fractional bar",
      { stems: { bass: { level: [{ bar: 0.5, value: 0 }] } } },
    ],
    ["a loud level", { stems: { bass: { level: [{ bar: 0, value: 7 }] } } }],
    [
      "a filter past 1",
      { stems: { bass: { filter: [{ bar: 0, value: 1.5 }] } } },
    ],
    [
      "two points on a bar",
      {
        stems: {
          bass: {
            level: [
              { bar: 1, value: 0 },
              { bar: 1, value: -3 },
            ],
          },
        },
      },
    ],
    [
      "too many points",
      {
        stems: {
          bass: {
            level: Array.from({ length: 33 }, (_, bar) => ({ bar, value: 0 })),
          },
        },
      },
    ],
    [
      "too many filter points in total",
      {
        stems: {
          bass: {
            filter: Array.from({ length: 30 }, (_, bar) => ({ bar, value: 0 })),
          },
          vocals: {
            filter: Array.from({ length: 30 }, (_, bar) => ({ bar, value: 0 })),
          },
        },
      },
    ],
  ])("rejects %s", (_label, raw) => {
    expect(() =>
      normalizeRemixAutomationInput(raw, ["bass", "vocals"]),
    ).toThrow();
  });

  it("reads stored lanes tolerantly, dropping stems that left the project", () => {
    expect(parseRemixAutomation(automation, ["bass"])).toEqual({
      schemaVersion: REMIX_AUTOMATION_SCHEMA_VERSION,
      stems: { bass: automation.stems.bass },
    });
    expect(parseRemixAutomation("x", ["bass"])).toBeNull();
  });
});

describe("automation curves (#2541)", () => {
  const points = [
    { atSec: 1, value: 0 },
    { atSec: 3, value: -1 },
  ];
  it("holds before the first point and after the last, straight lines between", () => {
    expect(laneValueAt(points, 0)).toBe(0);
    expect(laneValueAt(points, 2)).toBe(-0.5);
    expect(laneValueAt(points, 9)).toBe(-1);
  });

  it("maps the filter knob to cutoffs", () => {
    expect(filterCutoffs(0)).toEqual({ lowpassHz: 20000, highpassHz: 20 });
    expect(filterCutoffs(-1)).toEqual({ lowpassHz: 200, highpassHz: 20 });
    expect(filterCutoffs(1)).toEqual({ lowpassHz: 20000, highpassHz: 2000 });
    expect(filterCutoffs(-0.5).lowpassHz).toBeCloseTo(2000, 6);
  });

  it("drops points on bars the timeline no longer has", () => {
    expect(timedStemAutomation(automation, "vocals", [0, 2], 1)).toBeNull();
    expect(timedStemAutomation(automation, "vocals", [0, 2, 4], 2)).toEqual({
      level: null,
      filter: [{ atSec: 2, value: 0.3 }],
    });
  });

  it("puts the lanes after the Pro stages and before the gate, in output time", () => {
    const args = buildStemMixFfmpegArgs(
      [
        {
          path: "bass.wav",
          gainDb: 0,
          fxStemId: "bass",
          activeIntervals: [{ startSec: 0, endSec: 10 }],
          automation: {
            level: [
              { atSec: 2, value: 0 },
              { atSec: 4, value: -6 },
            ],
            filter: null,
          },
        },
      ],
      "out.mp3",
      {
        effects: {
          schemaVersion: "remix-fx/v4",
          master: { speed: 2 },
        } as never,
      },
    );
    const graph = args[args.indexOf("-filter_complex") + 1];
    const level = graph.indexOf("volume=volume='pow(10");
    const gate = graph.indexOf("volume=volume=min(1");
    expect(level).toBeGreaterThan(0);
    expect(gate).toBeGreaterThan(level);
    // 2 s and 4 s on the timeline are 1 s and 2 s at speed 2.
    expect(graph).toContain("gte(t\\,1)*lt(t\\,2)");
  });

  it("forces the fx graph for automation alone", () => {
    const args = buildStemMixFfmpegArgs(
      [
        {
          path: "bass.wav",
          gainDb: 0,
          fxStemId: "bass",
          automation: { level: null, filter: [{ atSec: 0, value: -0.5 }] },
        },
      ],
      "out.mp3",
    );
    expect(args[args.indexOf("-filter_complex") + 1]).toContain(
      "lowpass@alp0=f=2000",
    );
  });
});

describe("remix-automation-v1 parity fixture", () => {
  const built = buildFixture();
  if (process.env.UPDATE_REMIX_AUTOMATION_FIXTURE === "1") {
    writeFileSync(FIXTURE_PATH, `${JSON.stringify(built, null, 2)}\n`);
  }
  const fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));

  it("reproduces the committed points, samples and steps", () => {
    built.downbeats.forEach((t: number, i: number) =>
      expect(Math.abs(t - fixture.downbeats[i])).toBeLessThan(EPS),
    );
    expect(built.bass).toEqual(fixture.bass);
    built.samples.forEach((sample, i) => {
      for (const key of [
        "levelDb",
        "filter",
        "lowpassHz",
        "highpassHz",
      ] as const) {
        expect(Math.abs(sample[key] - fixture.samples[i][key])).toBeLessThan(
          1e-6,
        );
      }
    });
    expect(built.filterSteps).toEqual(fixture.filterSteps);
  });
});

/** RMS in dB of mono f32 samples over [from, to) seconds. */
function rmsDb(
  samples: Float32Array,
  from: number,
  to: number,
  sr = 48000,
): number {
  let sum = 0;
  const a = Math.round(from * sr);
  const b = Math.round(to * sr);
  for (let i = a; i < b; i += 1) sum += samples[i] * samples[i];
  return 10 * Math.log10(sum / (b - a) + 1e-20);
}

(FFMPEG ? describe : describe.skip)("automation render (real ffmpeg)", () => {
  it("moves the level and the filter where the lanes say", () => {
    const lanes = {
      level: [
        { atSec: 1, value: 0 },
        { atSec: 3, value: -24 },
      ],
      filter: [
        { atSec: 4, value: 0 },
        { atSec: 6, value: -1 },
      ],
    };
    const graph = `[0:a]${automationFilters(lanes, 0).join(",")}[out]`;
    const raw = execFileSync(
      "ffmpeg",
      [
        "-hide_banner",
        "-loglevel",
        "error",
        "-f",
        "lavfi",
        "-i",
        "sine=frequency=1000:duration=8:sample_rate=48000",
        "-filter_complex",
        graph,
        "-map",
        "[out]",
        "-f",
        "f32le",
        "-ac",
        "1",
        "pipe:1",
      ],
      { maxBuffer: 64 * 1024 * 1024 },
    );
    const x = new Float32Array(raw.buffer, raw.byteOffset, raw.length / 4);
    const base = rmsDb(x, 0.2, 0.8);
    // Level: 0 dB before 1 s, −12 dB at 2 s (±1 dB: per-frame steps), −24 dB from 3 s.
    expect(Math.abs(rmsDb(x, 1.95, 2.05) - (base - 12))).toBeLessThan(1);
    expect(Math.abs(rmsDb(x, 3.2, 3.8) - (base - 24))).toBeLessThan(0.5);
    // Filter: the 1 kHz tone is untouched at 0 and cut hard once the
    // low-pass is at 200 Hz (2nd order: about −28 dB at 1 kHz); the
    // 3.2–3.8 s window above already shows it untouched at 0.
    expect(rmsDb(x, 6.2, 7.8) - (base - 24)).toBeLessThan(-24);
  });
});
