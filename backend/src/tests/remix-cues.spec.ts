/**
 * Cue and loop points (#2540, S6d of #1903): the recipe, the timeline bar
 * grid shared with the beat maker, and the DJ extended plan and sidecar.
 * The parity block replays `remix-cues-v1.parity.json`, which the web
 * preview test also replays, so the studio's loops and the export's bars are
 * the same bars. Regenerate with UPDATE_REMIX_CUES_FIXTURE=1 (a rules
 * change needs a new schema or DSP version).
 */
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { deriveSectionGrid } from "../modules/remix/remix-arrangement";
import { beatHits } from "../modules/remix/remix-beat";
import {
  REMIX_CUES_SCHEMA_VERSION,
  cueLoopSpan,
  djCuesSidecar,
  djExtendedPlan,
  draftGridFor,
  normalizeRemixCuesInput,
  parseDraftGrid,
  parseRemixCues,
  timelineDownbeats,
  type DjExtendedPlan,
  type RemixCues,
} from "../modules/remix/remix-cues";
import { structureTimeline } from "../modules/remix/remix-structure";
import { djExportState } from "../modules/remix/remix-project.service";

const FIXTURE_PATH = join(__dirname, "../modules/remix/remix-cues-v1.parity.json");
const EPS = 1e-9;

const stems = [
  {
    audioFeatures: {
      schemaVersion: "stem-audio-features/v1",
      tempoBpm: 128,
      tempoConfidence: 0.9,
      firstBeatSec: 0.37,
      durationSeconds: 90,
    },
  },
];
const blocks = [{ section: 0 }, { section: 1 }, { section: 1 }, { section: 2 }, { section: 3 }, { section: 4 }, { section: 5 }];
const speed = 1.25;
const cues: RemixCues = {
  schemaVersion: REMIX_CUES_SCHEMA_VERSION,
  intro: { startBar: 0, bars: 8, repeats: 2 },
  outro: { startBar: 40, bars: 4, repeats: 3 },
};

function buildFixture() {
  const grid = deriveSectionGrid(stems as never)!;
  const segments = structureTimeline(grid, blocks);
  const downbeats = timelineDownbeats(grid, segments);
  const barSec = 240 / grid.bpm!;
  const durationSec = segments[segments.length - 1].outEndSec;
  const spans = {
    intro: cueLoopSpan(downbeats, barSec, durationSec, cues.intro!),
    outro: cueLoopSpan(downbeats, barSec, durationSec, cues.outro!),
  };
  const draftGrid = draftGridFor(grid, segments, speed)!;
  const plan = djExtendedPlan(draftGrid, cues) as DjExtendedPlan;
  const sidecar = djCuesSidecar(plan, draftGrid, "Neon Drift (Remix)", "Neon-Drift-Remix-DJ-Extended.mp3");
  return {
    schemaVersion: REMIX_CUES_SCHEMA_VERSION,
    note: "Generated by backend/src/tests/remix-cues.spec.ts (UPDATE_REMIX_CUES_FIXTURE=1). Replayed by web/src/lib/remixCues.test.ts.",
    grid: { bpm: grid.bpm, firstBeatSec: grid.firstBeatSec, sections: grid.sections },
    blocks,
    segments: segments.map(({ section, outStartSec, outEndSec }) => ({ section, outStartSec, outEndSec })),
    speed,
    cues,
    downbeats,
    spans,
    draftGrid,
    plan,
    sidecar,
  };
}

describe("cues recipe (#2540)", () => {
  it("normalizes and clears", () => {
    expect(normalizeRemixCuesInput({ intro: { startBar: 0, bars: 8, repeats: 2 } })).toEqual({
      schemaVersion: REMIX_CUES_SCHEMA_VERSION,
      intro: { startBar: 0, bars: 8, repeats: 2 },
      outro: null,
    });
    expect(normalizeRemixCuesInput(null)).toBeNull();
    expect(normalizeRemixCuesInput({ intro: null, outro: null })).toBeNull();
  });

  it.each([
    ["a string", "x"],
    ["a fractional bar", { intro: { startBar: 1.5, bars: 8, repeats: 1 } }],
    ["a negative bar", { intro: { startBar: -1, bars: 8, repeats: 1 } }],
    ["an odd length", { intro: { startBar: 0, bars: 3, repeats: 1 } }],
    ["no repeats", { intro: { startBar: 0, bars: 8, repeats: 0 } }],
    ["too many repeats", { intro: { startBar: 0, bars: 8, repeats: 9 } }],
    ["an outro before the intro ends", { intro: { startBar: 0, bars: 8, repeats: 1 }, outro: { startBar: 4, bars: 4, repeats: 1 } }],
    ["another schema", { schemaVersion: "remix-cues/v9", intro: null, outro: null }],
  ])("rejects %s", (_label, raw) => {
    expect(() => normalizeRemixCuesInput(raw)).toThrow();
    expect(parseRemixCues(raw)).toBeNull();
  });

  it("reads stored draft grids tolerantly", () => {
    expect(parseDraftGrid({ schemaVersion: "remix-draft-grid/v1", bpm: 120, downbeatsSec: [1, 0.5], timelineEndSec: 4 })).toBeNull();
    expect(parseDraftGrid({ schemaVersion: "remix-draft-grid/v1", bpm: 0, downbeatsSec: [0], timelineEndSec: 4 })).toBeNull();
    expect(parseDraftGrid("x")).toBeNull();
  });
});

describe("timeline bars (#2540)", () => {
  it("are the beat maker's bars", () => {
    const grid = deriveSectionGrid(stems as never)!;
    const segments = structureTimeline(grid, blocks);
    const kickEveryBar = Array.from({ length: 16 }, (_, i) => i === 0);
    const hits = beatHits(
      { kit: "punchy", pattern: { kick: kickEveryBar }, swing: 0 } as never,
      grid,
      segments,
    ).map((hit) => hit.timeSec);
    const downbeats = timelineDownbeats(grid, segments);
    // The beat skips a pickup block; every bar the beat plays is a downbeat.
    for (const t of hits) expect(downbeats.some((d) => Math.abs(d - t) < EPS)).toBe(true);
  });

  it("a loop past the end of the timeline does not fit", () => {
    expect(cueLoopSpan([0, 2, 4], 2, 6, { startBar: 2, bars: 1 })).toEqual({ startSec: 4, endSec: 6 });
    expect(cueLoopSpan([0, 2, 4], 2, 5.5, { startBar: 2, bars: 1 })).toBeNull();
    expect(cueLoopSpan([0, 2, 4], 2, 6, { startBar: 2, bars: 2 })).toBeNull();
    expect(cueLoopSpan([0, 2, 4], 2, 6, { startBar: 3, bars: 1 })).toBeNull();
  });
});

describe("DJ export state (#2540)", () => {
  const draftGrid = { schemaVersion: "remix-draft-grid/v1", bpm: 120, downbeatsSec: [0, 2, 4, 6], timelineEndSec: 8 };
  it("needs a completed draft with a grid the cues fit", () => {
    const cuesFit = { intro: { startBar: 0, bars: 2, repeats: 1 } };
    expect(djExportState({ generationMetadata: null, cues: cuesFit })).toEqual({ available: false, reason: "no_draft" });
    expect(djExportState({ generationMetadata: { status: "completed" }, cues: cuesFit })).toEqual({ available: false, reason: "no_draft_grid" });
    expect(djExportState({ generationMetadata: { status: "completed", draftGrid }, cues: null })).toEqual({ available: false, reason: "no_cues" });
    expect(
      djExportState({ generationMetadata: { status: "completed", draftGrid }, cues: { intro: { startBar: 2, bars: 4, repeats: 1 } } }),
    ).toEqual({ available: false, reason: "cues_outside_draft" });
    expect(djExportState({ generationMetadata: { status: "completed", draftGrid }, cues: cuesFit })).toEqual({ available: true, reason: null });
  });
});

describe("remix-cues-v1 parity fixture", () => {
  const built = buildFixture();
  if (process.env.UPDATE_REMIX_CUES_FIXTURE === "1") {
    writeFileSync(FIXTURE_PATH, `${JSON.stringify(built, null, 2)}\n`);
  }
  const fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));

  it("reproduces the committed downbeats, spans, plan and sidecar", () => {
    expect(built.downbeats).toHaveLength(fixture.downbeats.length);
    built.downbeats.forEach((t: number, i: number) => expect(Math.abs(t - fixture.downbeats[i])).toBeLessThan(EPS));
    expect(built.spans).toEqual(fixture.spans);
    expect(built.draftGrid).toEqual(fixture.draftGrid);
    expect(built.plan).toEqual(fixture.plan);
    expect(built.sidecar).toEqual(fixture.sidecar);
  });

  it("keeps the inserted bars on an even grid", () => {
    expect(fixture.sidecar.beatGrid.uniform).toBe(true);
    const inserted = (fixture.plan.insertedFrames as number) / fixture.plan.sampleRateHz;
    const barSec = 240 / fixture.draftGrid.bpm;
    expect(Math.abs(inserted - (8 * 2 + 4 * 3) * barSec)).toBeLessThan(1e-3);
  });
});
